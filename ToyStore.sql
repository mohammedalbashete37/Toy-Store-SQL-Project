--Q10-- How does the session-to-order conversion rate compare between first-time website visitors and repeat visitors?
-- ===================================================================================================================
SELECT 
    is_repeat_session,
    CAST(
        COUNT(DISTINCT o.order_id) * 100.0 
        / COUNT(DISTINCT w.website_session_id) 
        AS DECIMAL(5,2)
    ) AS Conversion_Rate
FROM website_sessions w
LEFT JOIN orders o
    ON w.website_session_id = o.website_session_id
GROUP BY is_repeat_session;
-- ============================================
--Result--
--First-Time Visitors : 6.64% Conversion Rate
--Repeat Visitors : 7.83% Conversion Rate  
-- ============================================



-- ==========================================================================================================================================
--Q11-- What is the sales performance of each product in terms of total units sold, unique orders, overall revenue, and net profit generated?
-- ==========================================================================================================================================
SELECT p.product_name,
       SUM(o.items_purchased) AS Total_Quantity_Sold,
       COUNT(o.order_id) AS Total_Orders,
       ROUND(SUM(o.price_usd),2) AS Total_Revenue,
       ROUND(SUM(o.price_usd) - SUM(o.cogs_usd), 2) AS Total_Profit
FROM orders o
JOIN products p
ON o.primary_product_id = p.product_id
GROUP BY p.product_name
ORDER BY Total_Profit DESC
