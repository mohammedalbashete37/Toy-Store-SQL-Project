--Q3-- How do session volumes and repeat visitor engagement levels vary across different traffic acquisition sources (UTM sources)?
-- ================================================================================================================================
SELECT 
    COALESCE(NULLIF(utm_source, 'NULL'), 'Unknown') AS utm_source,
    COUNT(*) AS Number_of_sessions,
    SUM(CASE WHEN is_repeat_session = 1 THEN 1 ELSE 0 END) * 100.0 / COUNT(*) AS repeated_sessions_percentage
