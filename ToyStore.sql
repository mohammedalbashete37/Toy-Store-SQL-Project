--Q5-- Which product consistently ranked as the top revenue generator for each individual year?
-- ============================================================================================
WITH Product_Revenue AS(
SELECT p.product_name,
       YEAR(o.created_at) AS Year,
       ROUND(SUM(o.price_usd),2) AS Total_Revenue,
       ROW_NUMBER() OVER(PARTITION BY YEAR(o.created_at) ORDER BY SUM(o.price_usd) DESC ) AS mr
FROM products p
JOIN orders o
    ON p.product_id = o.primary_product_id
GROUP BY p.product_name, YEAR(o.created_at)
)
SELECT
    Year,
    product_name,
    Total_Revenue
FROM Product_Revenue
WHERE mr = 1
ORDER BY Year;
-- =======================================================
--Result-- 
--2012: The Original Mr. Fuzzy | $129,274.14 Total Revenue
--2013: The Original Mr. Fuzzy | $314,709.24 Total Revenue
--2014: The Original Mr. Fuzzy | $762,859.86 Total Revenue
--2015: The Original Mr. Fuzzy | $212,924.63 Total Revenue  
-- ========================================================



