--Q15-- Which specific months generated total revenue that exceeded the overall monthly average across the entire business timeline?
-- =================================================================================================================================
WITH avg_monthly AS
(
    SELECT
        YEAR(created_at) AS Year,
        MONTH(created_at) AS Month,
        SUM(price_usd) AS Monthly_Revenue
    FROM orders
    GROUP BY
        YEAR(created_at),
        MONTH(created_at)
)
SELECT
    Year,
    Month,
    Monthly_Revenue
FROM avg_monthly
WHERE Monthly_Revenue > (
    SELECT AVG(Monthly_Revenue)
    FROM avg_monthly
)
ORDER BY Year, Month;
