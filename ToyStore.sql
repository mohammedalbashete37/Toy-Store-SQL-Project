--Q6-- What is the total revenue and corresponding refund amount generated by each individual product?
-- ===================================================================================================
SELECT p.product_name,
       ROUND(SUM(r.refund_amount_usd),2) AS Total_Refund,
       ROUND(SUM(oi.price_usd),2) AS Total_Revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
LEFT JOIN order_item_refunds r
    ON oi.order_item_id = r.order_item_id
GROUP BY p.product_name
-- =============================================================================
--Result-- 
--The Original Mr. Fuzzy: $1,211,057.78 Total Revenue $61,837.63 Total Refund
--The Forever Love Bear: $347,702.05 Total Revenue | $7,738.71 Total Refund
