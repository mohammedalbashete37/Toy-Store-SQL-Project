--Q16-- What is the average selling price and average unit cost across each individual product in the portfolio?
-- ==============================================================================================================
SELECT p.product_name,
       ROUND(AVG(o.price_usd), 2) AS Average_Selling_Price,
       ROUND(AVG(o.cogs_usd), 2) AS Average_Product_Cost
FROM orders o
JOIN products p
ON o.primary_product_id = p.product_id
GROUP BY p.product_name
