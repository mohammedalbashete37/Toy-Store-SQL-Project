-- ================================================================================
--Q1-- Which products in our catalog have generated over $100,000 in total revenue?
-- ================================================================================
SELECT p.product_name, SUM(o.price_usd) AS Total_Revenue
FROM orders o 
JOIN products p
ON p.product_id = o.primary_product_id
GROUP BY p.product_name
HAVING SUM(o.price_usd) > 100000
-- ==================================================================================
--Result-- The Original Mr. Fuzzy - The Forever Love Bear - The Birthday Sugar Panda
-- ==================================================================================



-- ==============================================================================================
--Q2-- How has the average order revenue evolved on a year-over-year basis between 2012 and 2015?
-- ==============================================================================================
SELECT 
    YEAR(created_at) AS Year, 
    ROUND(SUM(price_usd) / COUNT(DISTINCT order_id), 2) AS Average_Order_Value
FROM orders
GROUP BY YEAR(created_at)
ORDER BY Year;
-- ==========================
--Result--
-- 2012: $49.99
-- 2013: $52.81 (+5.6% YoY) 
-- 2014: $63.80 (+20.8% YoY)
-- 2015: $62.80 (-1.6% YoY)
-- ==========================



